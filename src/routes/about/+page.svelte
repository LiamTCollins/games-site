    <h1 class="text-3xl font-bold text-white mb-6">About daily-le.com</h1>

    <div class="space-y-4 text-slate-300 leading-relaxed">
      <p>daily-le.com is a collection of free daily puzzle games. Every day at midnight UTC, each game refreshes with a brand-new challenge — so there's always a reason to come back tomorrow.</p>

      <p>The site grew out of a love for the daily-puzzle format made popular by word games, reimagined across a wide range of topics: reflexes, geography, history, science, sports, and language. Each game is designed to be solved in a couple of minutes, with a shareable result so you can compare with friends.</p>

      <h2 class="text-xl font-semibold text-white pt-4">The games</h2>
      <ul class="list-disc list-inside space-y-1.5">
        <li><strong>Reactionle</strong> — stop a hidden timer as close to five seconds as you can.</li>
        <li><strong>Blindtap</strong> — the same challenge, with no visible timer at all.</li>
        <li><strong>Whodunit</strong> — identify a famous historical figure from a series of clues.</li>
        <li><strong>Sportle</strong> — name an obscure sport from its description.</li>
        <li><strong>Physicsle</strong> — identify a physics phenomenon from progressive hints.</li>
        <li><strong>Datele</strong> — guess the month and year of a historical event.</li>
        <li><strong>Languagle</strong> — identify a world language from a short text snippet.</li>
        <li><strong>Statele</strong> — name the US state or territory a city belongs to.</li>
        <li><strong>Elemently</strong> — guess a chemical element's atomic number with hot/cold feedback.</li>
        <li><strong>Capitdle</strong> — name the capital city of a given country.</li>
        <li><strong>Distantle</strong> — estimate the distance in kilometres between two cities.</li>
      </ul>

      <h2 class="text-xl font-semibold text-white pt-4">How it works</h2>
      <p>There are no accounts and no logins. Your daily progress and your streaks are stored privately in your own browser using local storage. Nothing is uploaded to a server. Clear your browser data and your history resets.</p>

      <p>Have feedback or an idea for a new game? We'd love to hear it.</p>
